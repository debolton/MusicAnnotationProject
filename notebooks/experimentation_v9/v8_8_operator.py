"""V8.8 adapter for Notebook 72.

Public API
----------
load_operator(v88_bundle_root, **options) -> OperatorContext
run_page(observed, authoritative_seed_mask, runtime_context, **page_options) -> PageResult

`v88_bundle_root` is the completed Notebook 52 run DIRECTORY.  The loader
resolves Notebook 50 from policy_bundle/policy_manifest.json and validates the
registered V8.8 REMOVE-only contract.  This module never reads clean/truth data.

Important operational boundary
------------------------------
Notebook 50's all_m3_oof_predictions_and_decisions.parquet contains registered
coordinates only for its frozen roster.  A page absent from that table cannot
be scored merely by pointing this adapter at the Notebook 52 directory.  For
such a page, Notebook 72 must supply a page decision table (page/y/x/safe_remove
and optionally probabilities) generated by the separately frozen deployable
scorer.  The adapter fails closed rather than pretending OOF decisions are a
new-page model.
"""
from __future__ import annotations
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Mapping, Optional
import hashlib, json, platform, sys, time
import cv2
import numpy as np

OPERATOR_ID = "v8.8-notebook72-adapter"
OPERATOR_VERSION = "2.0.0"
POLICY = "M5_REMOVE"
DECISION_FALLBACK = np.uint8(0)
DECISION_SAFE_REMOVE = np.uint8(1)


def _require(ok: Any, msg: str) -> None:
    if not bool(ok):
        raise RuntimeError(msg)


def _read_json(path: Path) -> dict[str, Any]:
    _require(path.is_file(), f"Missing JSON file: {path}")
    try:
        value=json.loads(path.read_text())
    except Exception as e:
        raise RuntimeError(f"Could not read JSON file {path}: {e}") from e
    _require(isinstance(value,dict), f"JSON root must be an object: {path}")
    return value


def _sha_file(path: Path) -> str:
    h=hashlib.sha256()
    with path.open('rb') as f:
        for b in iter(lambda:f.read(1024*1024),b''): h.update(b)
    return h.hexdigest()


def _sha_array(a: np.ndarray) -> str:
    a=np.ascontiguousarray(a); h=hashlib.sha256()
    h.update(str(a.dtype).encode()); h.update(str(a.shape).encode()); h.update(a.tobytes())
    return h.hexdigest()


def _resolve_existing(raw: Any, bases: list[Path], label: str) -> Path:
    _require(raw not in (None,''), f"Missing {label} in frozen manifest.")
    q=Path(str(raw)).expanduser()
    candidates=[q] if q.is_absolute() else [b/q for b in bases]
    hits=[]
    for c in candidates:
        if c.exists(): hits.append(c.resolve())
    hits=list(dict.fromkeys(hits))
    _require(len(hits)==1, f"Could not uniquely resolve {label}={raw!r}; matches={hits}")
    return hits[0]


@dataclass(frozen=True)
class OperatorContext:
    v88_bundle_root: Path
    notebook50_run: Path
    policy_manifest_path: Path
    predictor_schema_path: Path
    decision_table_path: Path
    verdict_path: Path
    policy_id: str
    ordered_predictors: tuple[str,...]
    decision_table: Any
    page_id: Optional[str]=None
    mask_is_prepared_m3: bool=False
    mask_dilation: int=2
    reconstruction_method: str='telea'
    inpaint_radius: int=3
    crop_margin: int=48
    strict_registered_roster: bool=True
    metadata: Mapping[str,Any]=field(default_factory=dict)

    def for_page(self, page_id: str, *, decisions: Any=None, **updates: Any) -> "OperatorContext":
        values={**self.__dict__, 'page_id':str(page_id)}
        if decisions is not None: values['decision_table']=decisions
        values.update(updates)
        return OperatorContext(**values)


@dataclass
class PageResult:
    corrected: np.ndarray
    baseline: np.ndarray
    prepared_mask: np.ndarray
    decisions: np.ndarray
    probabilities: dict[str,np.ndarray]
    changed: dict[str,np.ndarray]
    audit: dict[str,Any]
    safe_remove: np.ndarray
    m5_remove: np.ndarray


def _load_table(value: Any):
    import pandas as pd
    if isinstance(value,pd.DataFrame): return value.copy()
    path=Path(value)
    _require(path.is_file(), f"Missing decision table: {path}")
    if path.suffix.lower()=='.parquet': return pd.read_parquet(path)
    if path.suffix.lower()=='.csv': return pd.read_csv(path)
    raise RuntimeError(f"Unsupported decision table format: {path}")


def load_operator(v88_bundle_root: Any, **options: Any) -> OperatorContext:
    """Load a completed Notebook 52 run directory and resolve Notebook 50.

    Accepted first argument: str or pathlib.Path DIRECTORY only.
    Useful options: page_id, decision_table/registered_decisions,
    mask_is_prepared_m3, mask_dilation, reconstruction_method,
    inpaint_radius, crop_margin, notebook50_run.
    """
    root=Path(v88_bundle_root).expanduser().resolve()
    _require(root.is_dir(),
        "v88_bundle_root must be the completed Notebook 52 run DIRECTORY, not a file. "
        f"Received: {root}")
    verdict_path=root/'notebook52_verdict.json'
    policy_path=root/'policy_bundle'/'policy_manifest.json'
    inventory_path=root/'tables'/'notebook50_full_artifact_inventory.csv'
    golden_path=root/'tables'/'m5_remove_golden_master_semantic_hashes.csv'
    missing=[str(x) for x in (verdict_path,policy_path,inventory_path,golden_path) if not x.is_file()]
    _require(not missing,
        "Directory is not a complete Notebook 52 V8.8A run. Missing:\n  "+"\n  ".join(missing))
    verdict=_read_json(verdict_path); policy=_read_json(policy_path)
    _require(verdict.get('verdict')=='PASS_M5_REMOVE_FREEZE_READY_FOR_OPERATIONAL_BUILDER',
             f"Notebook 52 freeze is not operationally ready: {verdict.get('verdict')!r}")
    _require(policy.get('policy')==POLICY, f"Expected policy {POLICY}; got {policy.get('policy')!r}")
    _require(policy.get('safe_protect_runtime_enabled') is False, 'SAFE_PROTECT must remain disabled.')
    for key in ('retraining_performed','recalibration_performed','threshold_changed'):
        _require(policy.get(key) is False, f"Frozen policy mutation detected: {key}={policy.get(key)!r}")
    override=options.pop('notebook50_run',None)
    n50=_resolve_existing(override or policy.get('authoritative_notebook50_run'),
                          [root,root.parent,policy_path.parent], 'authoritative_notebook50_run')
    _require(n50.is_dir(), f"Resolved Notebook 50 path is not a directory: {n50}")
    schema_path=n50/'inputs'/'predictor_schema.json'
    decision_path=n50/'tables'/'all_m3_oof_predictions_and_decisions.parquet'
    _require(schema_path.is_file(), f"Missing Notebook 50 predictor schema: {schema_path}")
    _require(decision_path.is_file(), f"Missing Notebook 50 registered decision table: {decision_path}")
    schema=_read_json(schema_path)
    predictors=schema.get('ordered_predictors',schema.get('predictors',schema.get('ordered_features',[])))
    _require(isinstance(predictors,list) and predictors, 'Frozen ordered predictor schema is empty.')
    supplied=options.pop('decision_table',options.pop('registered_decisions',None))
    table=_load_table(supplied if supplied is not None else decision_path)
    required={'page','y','x','safe_remove'}
    _require(required.issubset(table.columns), f"Decision table missing columns: {sorted(required-set(table.columns))}")
    _require(not table.duplicated(['page','y','x']).any(), 'Decision table has duplicate page/y/x coordinates.')
    return OperatorContext(
        v88_bundle_root=root, notebook50_run=n50, policy_manifest_path=policy_path,
        predictor_schema_path=schema_path, decision_table_path=decision_path,
        verdict_path=verdict_path, policy_id=str(policy.get('policy_id','')),
        ordered_predictors=tuple(map(str,predictors)), decision_table=table,
        page_id=(lambda v: None if v is None else str(v))(options.pop('page_id',None)),
        mask_is_prepared_m3=bool(options.pop('mask_is_prepared_m3',False)),
        mask_dilation=int(options.pop('mask_dilation',2)),
        reconstruction_method=str(options.pop('reconstruction_method','telea')),
        inpaint_radius=int(options.pop('inpaint_radius',3)),
        crop_margin=int(options.pop('crop_margin',48)),
        strict_registered_roster=bool(options.pop('strict_registered_roster',True)),
        metadata={
            'operator_id':OPERATOR_ID,'operator_version':OPERATOR_VERSION,
            'notebook52_verdict':verdict.get('verdict'),
            'policy_manifest_sha256':_sha_file(policy_path),
            'predictor_schema_sha256':_sha_file(schema_path),
            'decision_table_sha256':_sha_file(decision_path),
            **dict(options.pop('metadata',{})),
        },
    ) if not options else (_ for _ in ()).throw(TypeError(f"Unknown load_operator options: {sorted(options)}"))


def _prepare_mask(seed: np.ndarray, dilation: int) -> np.ndarray:
    m=np.asarray(seed)>0
    _require(m.ndim==2,'Authoritative seed mask must be 2-D.')
    if dilation:
        _require(dilation>0,'mask_dilation must be non-negative.')
        k=cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(2*dilation+1,2*dilation+1))
        m=cv2.dilate(m.astype(np.uint8),k)>0
    return m


def _inpaint(observed: np.ndarray, mask: np.ndarray, method: str, radius: int) -> np.ndarray:
    flag={'telea':cv2.INPAINT_TELEA,'navier_stokes':cv2.INPAINT_NS}.get(method)
    _require(flag is not None, f"Unsupported reconstruction method: {method}")
    if not mask.any(): return observed.copy()
    out=cv2.inpaint(observed,mask.astype(np.uint8)*255,radius,flag)
    out[~mask]=observed[~mask]
    return out


def _page_rows(table: Any, page_id: str):
    import pandas as pd
    frame=table.copy()
    frame['page']=frame.page.astype(str)
    frame=frame[frame.page==str(page_id)].copy()
    _require(not frame.empty,
        f"Page {page_id!r} is absent from the registered Notebook 50 decision table. "
        "Supply that page's frozen deployable-scorer decision table via "
        "context.for_page(page_id, decisions=...) or load_operator(..., decision_table=...).")
    for c in ('y','x'): frame[c]=pd.to_numeric(frame[c],errors='raise').astype(int)
    frame['safe_remove']=frame.safe_remove.astype(bool)
    return frame


def run_page(observed: np.ndarray, authoritative_seed_mask: np.ndarray,
             runtime_context: OperatorContext, **page_options: Any) -> PageResult:
    """Run one clean-free page. `page_id` may be in context or keyword options."""
    started=time.perf_counter()
    _require(isinstance(runtime_context,OperatorContext),
             'runtime_context must be the object returned by load_operator().')
    page_id=page_options.pop('page_id',runtime_context.page_id)
    decisions_override=page_options.pop('decision_table',page_options.pop('registered_decisions',None))
    _require(not page_options, f"Unknown run_page options: {sorted(page_options)}")
    _require(page_id not in (None,''),
             'run_page needs page_id. Use load_operator(..., page_id=...) or run_page(..., page_id=...).')
    obs=np.asarray(observed); seed=np.asarray(authoritative_seed_mask)
    _require(obs.ndim==2 and obs.dtype==np.uint8,'observed must be a 2-D uint8 page.')
    _require(seed.shape==obs.shape,'Observed page and authoritative mask shape mismatch.')
    dilation=0 if runtime_context.mask_is_prepared_m3 else runtime_context.mask_dilation
    m3=_prepare_mask(seed,dilation)
    table=_load_table(decisions_override) if decisions_override is not None else runtime_context.decision_table
    rows=_page_rows(table,str(page_id))
    h,w=obs.shape; ys=rows.y.to_numpy(int); xs=rows.x.to_numpy(int)
    _require((ys>=0).all() and (xs>=0).all() and (ys<h).all() and (xs<w).all(),
             f"{page_id}: decision coordinate outside observed canvas {obs.shape}.")
    selected=rows.safe_remove.to_numpy(bool)
    safe=np.zeros(obs.shape,bool); safe[ys[selected],xs[selected]]=True
    _require(not np.any(safe & ~m3), f"{page_id}: SAFE_REMOVE expands beyond authoritative M3.")
    m5=m3 & ~safe
    baseline=_inpaint(obs,m3,runtime_context.reconstruction_method,runtime_context.inpaint_radius)
    corrected=_inpaint(obs,m5,runtime_context.reconstruction_method,runtime_context.inpaint_radius)
    # M5 subtraction means SAFE_REMOVE pixels are not reconstructed; observed bytes survive exactly.
    corrected[safe]=obs[safe]
    corrected[~m3]=obs[~m3]
    p_remove=np.full(obs.shape,np.nan,np.float32)
    pcol=next((c for c in ('p_remove','remove_probability','calibrated_remove_probability') if c in rows.columns),None)
    if pcol:
        vals=np.asarray(rows[pcol],dtype=float)
        _require(np.isfinite(vals).all(),'Non-finite registered probabilities.')
        p_remove[ys,xs]=vals.astype(np.float32)
    decisions=np.full(obs.shape,DECISION_FALLBACK,np.uint8); decisions[safe]=DECISION_SAFE_REMOVE
    changed_obs=corrected!=obs; changed_base=corrected!=baseline
    _require(np.array_equal(corrected[~m3],obs[~m3]),'Outside-authority drift detected.')
    _require(np.array_equal(corrected[~safe],baseline[~safe]),
             'V8.8 result differs from exact M3 fallback outside SAFE_REMOVE.')
    audit={
        **dict(runtime_context.metadata),'page_id':str(page_id),'policy_id':runtime_context.policy_id,
        'policy':'M5_REMOVE = M3 & ~SAFE_REMOVE','safe_protect_runtime_enabled':False,
        'clean_or_truth_input_used':False,'v88_bundle_root':str(runtime_context.v88_bundle_root),
        'notebook50_run':str(runtime_context.notebook50_run),'observed_sha256':_sha_array(obs),
        'authoritative_seed_mask_sha256':_sha_array((seed>0).astype(np.uint8)),
        'prepared_mask_sha256':_sha_array(m3.astype(np.uint8)),
        'safe_remove_sha256':_sha_array(safe.astype(np.uint8)),
        'm5_remove_sha256':_sha_array(m5.astype(np.uint8)),
        'baseline_sha256':_sha_array(baseline),'corrected_sha256':_sha_array(corrected),
        'decisions_sha256':_sha_array(decisions),'prepared_mask_pixels':int(m3.sum()),
        'safe_remove_pixels':int(safe.sum()),'m5_remove_pixels':int(m5.sum()),
        'changed_from_observed_pixels':int(changed_obs.sum()),
        'changed_from_baseline_pixels':int(changed_base.sum()),
        'outside_mask_drift_pixels':int(np.sum(corrected[~m3]!=obs[~m3])),
        'python':sys.version,'platform':platform.platform(),'numpy':np.__version__,
        'opencv':cv2.__version__,'elapsed_seconds':time.perf_counter()-started,
    }
    return PageResult(corrected,baseline,m3,decisions,{'p_remove':p_remove},
                      {'from_observed':changed_obs,'from_baseline':changed_base,
                       'valid_intervention':m3.copy()},audit,safe,m5)


__all__=['OPERATOR_ID','OPERATOR_VERSION','OperatorContext','PageResult','load_operator','run_page']
